-- Lowercase for search. string.lower depends on the C library's locale and can corrupt UTF-8 bytes, so fold
-- A-Z by byte range (locale-independent in Lua patterns) and the UTF-8 Latin-1 capitals (Ä Ö Ü É ...) by hand.
function ns.Lower(s)
	s = (s or ""):gsub("[A-Z]", function(c) return string.char(c:byte() + 32) end)
	return (s:gsub("\195([\128-\158])", function(c)
		local b = c:byte()
		if b == 151 then return "\195" .. c end -- × has no lowercase
		return "\195" .. string.char(b + 32)
	end))
end

